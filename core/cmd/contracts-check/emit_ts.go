package main

// -emit-ts writes a TypeScript file in which every valid fixture is a literal
// annotated with the type generated from its schema definition. Running tsc
// over it catches drift between the schemas, the generated types and the
// fixtures with literal types intact; importing the JSON files instead would
// widen every enum to string. Invalid fixtures are not emitted: TypeScript
// cannot express most of what makes them invalid.

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

var nonIdent = regexp.MustCompile(`[^A-Za-z0-9]+`)

func emitTS(dir, out string, fixtures []fixture) error {
	var body bytes.Buffer
	types := map[string]bool{}
	for _, fx := range fixtures {
		if !fx.Valid {
			continue
		}
		_, def, ok := strings.Cut(fx.Schema, "#/$defs/")
		if !ok {
			return fmt.Errorf("%s: schema %s does not name a $defs entry", fx.File, fx.Schema)
		}
		raw, err := os.ReadFile(filepath.Join(dir, fx.File))
		if err != nil {
			return err
		}
		var pretty bytes.Buffer
		if err := json.Indent(&pretty, raw, "", "  "); err != nil {
			return fmt.Errorf("%s: %w", fx.File, err)
		}
		name := "fx_" + strings.Trim(nonIdent.ReplaceAllString(strings.TrimSuffix(strings.TrimPrefix(fx.File, "fixtures/"), ".json"), "_"), "_")
		types[def] = true
		fmt.Fprintf(&body, "// %s\nexport const %s: %s = %s;\n\n", fx.File, name, def, strings.TrimSpace(pretty.String()))
	}
	names := make([]string, 0, len(types))
	for t := range types {
		names = append(names, t)
	}
	sort.Strings(names)
	var head bytes.Buffer
	head.WriteString("// Generated by core/cmd/contracts-check -emit-ts from contracts/assistant/fixtures. Do not edit.\n")
	head.WriteString("// tsc type-checks every valid fixture against the generated contract types.\n")
	fmt.Fprintf(&head, "import type { %s } from \"./assistant\";\n\n", strings.Join(names, ", "))
	return os.WriteFile(out, append(head.Bytes(), body.Bytes()...), 0o644)
}
